function glifoFor(categoria) {
  return categoria === "arte" ? "🖼️" : "⛪";
}

function buildCardVisual(item, categoria, mini) {
  const wrapCls = mini ? `mini-visual ${categoria}` : `card-visual ${categoria}`;
  const glCls   = mini ? "mini-glyph" : "card-glyph";
  const imgTag  = item.img ? `<img src="${item.img}" alt="${item.nome}" loading="lazy" decoding="async" onerror="this.remove()">` : "";
  const pillLabel = categoria === "arte" ? t("pill_mostra") : t("pill_storico");
  const pill    = mini ? "" : `<span class="card-type-pill ${categoria}">${pillLabel}</span>`;
  return `<div class="${wrapCls}">${imgTag}<span class="${glCls}">${glifoFor(categoria)}</span>${pill}</div>`;
}


let MOSTRE = [];

function getLuogoBreve(it) {
  if (currentLang !== "it") {
    const k = `breve_${currentLang}`;
    if (it[k]) return it[k];
  }
  return it.breve;
}

function getLuogoDescrizione(it) {
  if (currentLang !== "it") {
    const k = `descrizione_${currentLang}`;
    if (it[k] && it[k].length) return it[k];
  }
  return it.descrizione;
}

function loadMostre() {
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  MOSTRE = MOSTRE_DATA.filter(m => {
    const parts = m.data_fine.split("/");
    if (parts.length !== 3) return true;
    const fine = new Date(+parts[2], +parts[1] - 1, +parts[0]);
    return fine >= today;
  });
  renderListaMostre();
  renderSheet();
  if (typeof markersLayer !== "undefined") drawMarkers();
}


function renderSheet() {
  let items = [];
  if (attivi.storico) items = items.concat(LUOGHI.map(i => ({ ...i, cat: "storico" })));
  if (attivi.arte)    items = items.concat(MOSTRE.map(i => ({ ...i, cat: "arte" })));
  document.getElementById("sheetList").innerHTML = items.map(it => `
    <div class="mini-card" onclick="openDetail('${it.id}','${it.cat}')">
      ${buildCardVisual(it, it.cat, true)}
      <div class="mini-card-title">${it.nome}</div>
    </div>`).join("");
}

function initMap() {
  if (typeof L === "undefined") { setTimeout(initMap, 80); return; }
  map = L.map("map", {
    zoomControl: false, attributionControl: false,
    zoomSnap: 1, zoomDelta: 1, wheelPxPerZoomLevel: 60,
    zoomAnimation: true, fadeAnimation: true, markerZoomAnimation: true,
    preferCanvas: true
  }).setView([41.1280, 16.8710], 15);
  L.control.attribution({ position: "bottomleft", prefix: false })
   .addAttribution('© <a href="https://carto.com/">CARTO</a> · © <a href="https://www.openstreetmap.org/copyright">OSM</a>')
   .addTo(map);
  tileLayer = L.tileLayer(MAP_TILES[currentMapStyle] || MAP_TILES.streets, {
    maxZoom: 20, subdomains: currentMapStyle === "streets" ? "abcd" : "",
    attribution: currentMapStyle === "satellite" ? "Tiles &copy; Esri" : "",
    updateWhenZooming: false, keepBuffer: 8, crossOrigin: true
  }).addTo(map);
  markersLayer = L.layerGroup().addTo(map);
  drawMarkers();
  fitToMarkers();
}

function fitToMarkers() {
  const pts = [];
  if (attivi.storico) LUOGHI.forEach(it => pts.push([it.lat, it.lng]));
  if (attivi.arte)    MOSTRE.forEach(it => it.lat && pts.push([it.lat, it.lng]));
  if (pts.length && map) map.fitBounds(pts, { padding: [50, 50], maxZoom: 16 });
}

function makeIcon(categoria, label) {
  const cls = categoria === "arte" ? "arte" : "storico";
  return L.divIcon({
    className: "",
    html: `<div class="pin ${cls}"><span class="pin-glyph">${glifoFor(categoria)}</span><span class="pin-label">${label}</span></div>`,
    iconSize: [null, null], iconAnchor: [14, 34]
  });
}

